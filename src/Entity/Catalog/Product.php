<?php

namespace App\Entity\Catalog;

use App\Repository\ProductRepository;
use Doctrine\ORM\Mapping as ORM;

#[ORM\Entity(repositoryClass: ProductRepository::class)]
#[ORM\Table(name: 'products')]
class Product
{
    #[ORM\Id]
    #[ORM\GeneratedValue(strategy: 'IDENTITY')]
    #[ORM\Column(type: 'bigint')]
    private ?int $id = null;

    #[ORM\Column(type: 'string', length: 100)]
    private ?string $name = null;

    #[ORM\Column(type: 'string', unique: true, length: 20, options: ['fixed' => false])]
    private ?string $code = null;

    #[ORM\Column(type: 'text')]
    private ?string $description = null;

    #[ORM\Column(type: 'decimal', precision: 10, scale: 2)]
    private ?string $priceRub = null;

    #[ORM\ManyToOne(targetEntity: ProductStatusType::class, fetch: 'LAZY')]
    #[ORM\JoinColumn(name: 'status_type_id', referencedColumnName: 'id', nullable: false)]
    private ?ProductStatusType $statusType = null;

    #[ORM\ManyToOne(targetEntity: Category::class, fetch: 'LAZY')]
    #[ORM\JoinColumn(name: 'category_id', referencedColumnName: 'id', nullable: false)]
    private ?Category $category = null;

    #[ORM\Column(type: 'datetime_immutable', nullable: false)]
    private ?\DateTimeImmutable $createdAt = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(string $name): self
    {
        $this->name = $name;

        return $this;
    }

    public function getCode(): ?string
    {
        return $this->code;
    }

    public function setCode(string $code): self
    {
        $this->code = $code;

        return $this;
    }

    public function getDescription(): ?string
    {
        return $this->description;
    }

    public function setDescription(string $description): self
    {
        $this->description = $description;

        return $this;
    }

    public function getPriceRub(): ?string
    {
        return $this->priceRub;
    }

    public function setPriceRub(string $priceRub): self
    {
        $this->priceRub = $priceRub;

        return $this;
    }

    public function getStatusType(): ?ProductStatusType
    {
        return $this->statusType;
    }

    public function setStatusType(ProductStatusType $statusType): self
    {
        $this->statusType = $statusType;

        return $this;
    }

    public function getCategory(): ?Category
    {
        return $this->category;
    }

    public function setCategory(Category $category): self
    {
        $this->category = $category;

        return $this;
    }

    public function getCreatedAt(): ?\DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function setCreatedAt(\DateTimeImmutable $createdAt): self
    {
        $this->createdAt = $createdAt;

        return $this;
    }
}
